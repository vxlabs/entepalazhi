import "server-only";
import { mkdirSync } from "node:fs";
import path from "node:path";
import Database from "better-sqlite3";

/**
 * The only place the app opens the database: one SQLite file at
 * DATABASE_PATH, opened once per server process.
 *
 * Every statement goes through query()/execute() with named parameters
 * (`@name` in the text, `{ name: value }` alongside). Values are never
 * concatenated into SQL. The few helpers below that build statements take
 * table and column names from code, never from a request.
 *
 * Storage conventions (see db/migrations/0001_init.sql):
 * - ids are lowercase UUID strings, generated by the column default
 * - timestamps are ISO-8601 UTC strings ("2026-11-21T05:37:24.123Z"), so
 *   they compare correctly as text
 * - calendar dates are "YYYY-MM-DD" strings
 * - booleans are 0/1 in columns declared `boolean`, returned as true/false
 */

type Db = Database.Database;

const globalForDb = globalThis as unknown as { __entepalazhiDb?: Db };

function getDb(): Db {
  if (!globalForDb.__entepalazhiDb) {
    const file = process.env.DATABASE_PATH;
    if (!file) throw new Error("DATABASE_PATH is not set.");
    mkdirSync(path.dirname(path.resolve(file)), { recursive: true });

    const db = new Database(file);
    db.pragma("journal_mode = WAL");
    db.pragma("busy_timeout = 5000");
    // Cascading deletes in the schema depend on this; SQLite has it off by default.
    db.pragma("foreign_keys = ON");
    globalForDb.__entepalazhiDb = db;
  }
  return globalForDb.__entepalazhiDb;
}

/** SQL for "now", in the same format the timestamp columns are stored in. */
export const NOW = "strftime('%Y-%m-%dT%H:%M:%fZ', 'now')";

export type SqlValue = string | number | boolean | Date | null | undefined;
export type SqlParams = Record<string, SqlValue>;

const PARAM = /@([A-Za-z_][A-Za-z0-9_]*)/g;

/** Converts values to what SQLite stores, and passes only the parameters
 * the statement actually names. */
function bind(text: string, params: SqlParams): Record<string, string | number | null> {
  const out: Record<string, string | number | null> = {};
  for (const [, name] of text.matchAll(PARAM)) {
    if (name in out) continue;
    if (!(name in params)) throw new Error(`Missing SQL parameter: @${name}`);
    const value = params[name];
    if (value === null || value === undefined) out[name] = null;
    else if (typeof value === "boolean") out[name] = value ? 1 : 0;
    else if (value instanceof Date) out[name] = value.toISOString();
    else out[name] = value;
  }
  return out;
}

/** Turns 0/1 back into true/false for columns declared `boolean`. */
function normalise<T>(statement: Database.Statement, rows: unknown[]): T[] {
  const booleans = statement
    .columns()
    .filter((c) => c.type?.toLowerCase() === "boolean")
    .map((c) => c.name);
  if (booleans.length === 0) return rows as T[];

  return rows.map((row) => {
    const out = { ...(row as Record<string, unknown>) };
    for (const name of booleans) {
      if (out[name] !== null && out[name] !== undefined) out[name] = Boolean(out[name]);
    }
    return out as T;
  });
}

export async function query<T>(text: string, params: SqlParams = {}): Promise<T[]> {
  const statement = getDb().prepare(text);
  return normalise<T>(statement, statement.all(bind(text, params)));
}

export async function queryOne<T>(text: string, params: SqlParams = {}): Promise<T | null> {
  const rows = await query<T>(text, params);
  return rows[0] ?? null;
}

/** Runs a statement and returns the number of rows it changed. */
export async function execute(text: string, params: SqlParams = {}): Promise<number> {
  return getDb().prepare(text).run(bind(text, params)).changes;
}

/**
 * Runs `fn` inside one transaction: all of its statements apply, or none.
 * `fn` must be synchronous between its awaits on query()/execute() - those
 * resolve immediately, since the driver is synchronous.
 */
export async function transaction<T>(fn: () => Promise<T>): Promise<T> {
  const db = getDb();
  db.exec("begin immediate");
  try {
    const result = await fn();
    db.exec("commit");
    return result;
  } catch (error) {
    if (db.inTransaction) db.exec("rollback");
    throw error;
  }
}

const IDENTIFIER = /^[a-z_][a-z0-9_]*$/;

function assertIdentifier(name: string): string {
  if (!IDENTIFIER.test(name)) throw new Error(`Unsafe SQL identifier: ${name}`);
  return name;
}

/** INSERT one row; returns the new row's id. */
export async function insertRow(table: string, values: SqlParams): Promise<string> {
  const columns = Object.keys(values).map(assertIdentifier);
  const rows = await query<{ id: string }>(
    `insert into ${assertIdentifier(table)} (${columns.join(", ")})
     values (${columns.map((c) => `@${c}`).join(", ")})
     returning id`,
    values,
  );
  return rows[0].id;
}

/** UPDATE the row with the given id; returns the number of rows changed. */
export async function updateRowById(table: string, id: string, values: SqlParams): Promise<number> {
  const columns = Object.keys(values).map(assertIdentifier);
  if (columns.length === 0) return 0;
  return execute(
    `update ${assertIdentifier(table)} set ${columns.map((c) => `${c} = @${c}`).join(", ")} where id = @__id`,
    { ...values, __id: id },
  );
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** Guard for ids that arrive in URLs: rejects anything that cannot be a
 * row id before it reaches a query. */
export function isUuid(value: unknown): value is string {
  return typeof value === "string" && UUID.test(value);
}

/** Escapes LIKE wildcards so user search text matches literally. Use with
 * `like @q escape '\'`. */
export function likePattern(term: string): string {
  return `%${term.replace(/[\\%_]/g, (ch) => `\\${ch}`)}%`;
}
