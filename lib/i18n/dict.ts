export function getDictionary(locale: Locale): Dictionary {
  return dict[locale];
}

/** Simple {placeholder} interpolation - no plural rules beyond one/other. */
export function t(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`));
}

export function tCount(d: Dictionary, count: number): string {
  const template = count === 1 ? d.projects.count_one : d.projects.count_other;
  return t(template, { count });
}
